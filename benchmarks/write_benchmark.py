#!/usr/bin/env python3
"""Write BENCHMARK.md from the frozen external-baseline receipts.

The document is generated from JSON receipts so that displayed medians,
spreads, target enclosures, revisions, and resource limits cannot drift from
the recorded runs.
"""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXTERNAL = ROOT / "benchmarks" / "external"

ORDER = [
    ("elegant-source", "4/5", "EJM source, v=0.80"),
    ("elegant-source", "21/25", "EJM source, v=0.84"),
    ("elegant-detector", "43/50", "EJM detector, v=0.86"),
    ("renou-detector", "93/100", "Renou detector, u²=0.85, v=0.93"),
    ("renou-detector", "19/20", "Renou detector, u²=0.85, v=0.95"),
    ("renou", "17/20", "Noiseless Renou, u²=0.85"),
]


def read(name: str):
    return json.loads((EXTERNAL / name).read_text())


def target_records():
    records = json.loads((ROOT / "benchmarks" / "target-bounds.json").read_text())["records"]
    indexed = {(r["family"], r["parameter"]): r for r in records}
    missing = [(family, parameter) for family, parameter, _ in ORDER
               if (("renou-u2" if family == "renou" else family), parameter) not in indexed]
    if missing:
        raise ValueError(f"Missing target-bound records: {missing}")
    return indexed


def score(summary, solver, family, parameter, budget):
    rows = [r for r in summary
            if r["solver"] == solver and r["family"] == family
            and r["parameter"] == parameter and r["budget_seconds"] == budget]
    if len(rows) != 1:
        raise ValueError(f"Expected one summary row for {solver}, {family}, {parameter}, {budget}")
    row = rows[0]
    if row["n"] == 0:
        return "not reached"
    return f'{row["median_l2"]:.3g} [{row["min_l2"]:.3g}, {row["max_l2"]:.3g}]'


def target_table(bounds):
    lines = [
        "| Stress point | stored-target sqrt(E) | delta_target | principal U |",
        "|---|---:|---:|---:|",
    ]
    for family, parameter, label in ORDER:
        target_family = "renou-u2" if family == "renou" else family
        row = bounds[(target_family, parameter)]
        lines.append(
            f"| {label} | {short(row['stored_model_target_L2'])} | "
            f"{short(row['delta_target_L2_upper'])} | "
            f"{short(row['U_sqrtE_plus_delta_target_upper'], 12)} |"
        )
    return lines


def short(value, digits=6):
    """Compact display value; the complete outward enclosure stays in JSON."""
    if value in (0, "0", "0.0"):
        return "0"
    return f"{float(value):.{digits}g}"


def solver_table(summary, solver):
    lines = [
        "| Stress point | 10 s median [spread] | 60 s median [spread] | 300 s median [spread] |",
        "|---|---:|---:|---:|",
    ]
    for family, parameter, label in ORDER:
        lines.append(
            f"| {label} | {score(summary, solver, family, parameter, 10)} | "
            f"{score(summary, solver, family, parameter, 60)} | "
            f"{score(summary, solver, family, parameter, 300)} |"
        )
    return lines


